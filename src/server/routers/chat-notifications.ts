import { z } from 'zod'
import { createTRPCRouter, protectedProcedure } from '@/lib/trpc/server'
import { postToChatWebhook, isValidWebhookUrl, weeklyDigestCard } from '@/lib/google-chat'

const APP_URL = process.env.AUTH_URL ?? 'https://faro-app-303070777698.southamerica-east1.run.app'

export type NotificationPref =
  | 'chat_new_project'
  | 'chat_mentions'
  | 'chat_deadlines'
  | 'chat_weekly_digest'
  | 'chat_recurring_created'

const PREF_KEYS = [
  'chat_new_project',
  'chat_mentions',
  'chat_deadlines',
  'chat_weekly_digest',
  'chat_recurring_created',
] as const

/** Default to "on" if the pref hasn't been explicitly disabled. */
export function isEnabled(
  prefs: Record<string, boolean> | null | undefined,
  key: NotificationPref,
): boolean {
  if (!prefs) return true
  return prefs[key] !== false
}

export const chatNotificationsRouter = createTRPCRouter({
  /** Returns whether a webhook is configured + current preferences. */
  status: protectedProcedure.query(async ({ ctx }) => {
    const { data } = await ctx.supabase
      .from('organizations')
      .select('google_chat_webhook_url, notification_prefs')
      .eq('id', ctx.me.org_id)
      .single()
    const url = data?.google_chat_webhook_url ?? null
    const prefs = (data?.notification_prefs ?? {}) as Record<string, boolean>
    return {
      configured: !!url,
      preview: url ? url.replace(/(\?.*$)/, '?…') : null,
      prefs: Object.fromEntries(PREF_KEYS.map(k => [k, isEnabled(prefs, k)])) as Record<NotificationPref, boolean>,
    }
  }),

  /** Toggle a single notification preference. */
  setPref: protectedProcedure
    .input(z.object({
      key: z.enum(PREF_KEYS),
      enabled: z.boolean(),
    }))
    .mutation(async ({ ctx, input }) => {
      // Read-modify-write the JSONB column (small object, no concurrency concern at our scale).
      const { data: org } = await ctx.supabase
        .from('organizations').select('notification_prefs').eq('id', ctx.me.org_id).single()
      const next = { ...(org?.notification_prefs ?? {}), [input.key]: input.enabled }
      const { error } = await ctx.supabase
        .from('organizations')
        .update({ notification_prefs: next })
        .eq('id', ctx.me.org_id)
      if (error) throw error
      return { success: true }
    }),

  setWebhook: protectedProcedure
    .input(z.object({ url: z.string().trim() }))
    .mutation(async ({ ctx, input }) => {
      if (input.url && !isValidWebhookUrl(input.url)) {
        throw new Error('URL inválida. Debe ser https://chat.googleapis.com/v1/spaces/...')
      }
      const { error } = await ctx.supabase
        .from('organizations')
        .update({ google_chat_webhook_url: input.url || null })
        .eq('id', ctx.me.org_id)
      if (error) throw error
      return { success: true }
    }),

  sendTest: protectedProcedure.mutation(async ({ ctx }) => {
    const { data: org } = await ctx.supabase
      .from('organizations')
      .select('google_chat_webhook_url, name')
      .eq('id', ctx.me.org_id)
      .single()
    if (!org?.google_chat_webhook_url) throw new Error('Sin webhook configurado.')

    await postToChatWebhook(org.google_chat_webhook_url, {
      text: `🚦 *FARO* conectado a este espacio. Vas a recibir aquí notificaciones de proyectos, deadlines y digest semanal del workspace _${org.name}_.`,
    })
    return { success: true }
  }),

  /**
   * Send the last-generated weekly digest payload to the org's Chat webhook.
   * The client passes the digest content (already generated by digests.weekly)
   * so we don't burn another Gemini call just to send it.
   */
  sendDigest: protectedProcedure
    .input(z.object({
      headline: z.string(),
      highlights: z.array(z.string()),
      risks: z.array(z.string()),
      asks: z.array(z.string()),
      nextWeekFocus: z.string(),
    }))
    .mutation(async ({ ctx, input }) => {
      const { data: org } = await ctx.supabase
        .from('organizations')
        .select('google_chat_webhook_url')
        .eq('id', ctx.me.org_id)
        .single()
      if (!org?.google_chat_webhook_url) throw new Error('Sin webhook configurado.')

      await postToChatWebhook(
        org.google_chat_webhook_url,
        weeklyDigestCard({
          ...input,
          url: `${APP_URL}/dashboard/reports`,
        }),
      )
      return { success: true }
    }),
})
